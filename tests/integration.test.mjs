import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawn, spawnSync } from 'node:child_process';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { once } from 'node:events';

const password='senha extensa para teste';
test('Sinalização, autorização e persistência de ponta a ponta', {timeout:22000},async t=>{
  const directory=mkdtempSync(join(tmpdir(),'central-rpg-test-'));
  const env={...process.env,HOST:'127.0.0.1',PORT:'0',DATA_DIR:directory,SECURE_COOKIE:'0'};
  const bootstrap=spawnSync(process.execPath,['server.mjs','bootstrap','gm@example.com','Mestre'],{env,encoding:'utf8'});
  assert.equal(bootstrap.status,0,bootstrap.stderr);
  let child;
  let base;
  async function boot() {
    child=spawn(process.execPath,['server.mjs'],{env});
    child.stderr.resume();
    const [started]=await once(child.stdout,'data');
    base=started.toString().trim().match(/http:\/\/[^\s]+/)[0];
  }
  async function stop() {if(child.exitCode===null && child.signalCode===null) {child.kill(); await once(child,'exit');}}
  await boot();
  t.after(async()=>{await stop();rmSync(directory,{recursive:true,force:true});});
  async function request(cookie,route,body,status=200) {
    const response=await fetch(base+'/api/'+route,{method:body===undefined?'GET':'POST',headers:{Cookie:cookie,'Content-Type':'application/json'},body:body===undefined?undefined:JSON.stringify(body)});
    const content=response.headers.get('content-type')||'';
    const data=content.startsWith('application/json')?await response.json():await response.text();
    assert.equal(response.status,status,route+' '+JSON.stringify(data));
    return {data,cookie:response.headers.get('set-cookie')?.split(';')[0]};
  }
  const activate=async code=>(await request('','activate',{code,password})).cookie;
  const gm=await activate(bootstrap.stdout.trim().split(' ').at(-1));
  await request('','campaigns',undefined,401);
  const a=(await request(gm,'campaigns',{name:'Vale das Sombras'},201)).data.slug;
  const b=(await request(gm,'campaigns',{name:'Cidade de Vidro'},201)).data.slug;
  const inA='c/'+a+'/';
  const inB='c/'+b+'/';
  async function member(email,name,campaign=inA,role='player') {
    const {data}=await request(gm,campaign+'member',{email,name,role});
    return activate(data.code);
  }
  const j1=await member('um@example.com','Jogador Um');
  const j2=await member('dois@example.com','Jogador Dois');
  const j3=await member('tres@example.com','Jogador Três',inB);
  const registeredMaster=(await request('','register',{name:'Nova Mestra',password},201)).cookie;
  const newPlayer=(await request('','register',{name:'Nova Jogadora',password},201)).cookie;
  await request('','register',{name:'NOVA  JOGADORA',password},409);
  const room=(await request(registeredMaster,'campaigns',{name:'Sala do Farol'},201)).data;
  const inRoom='c/'+room.slug+'/';
  assert.match(room.roomCode,/^[0-9A-F]{16}$/);
  await request(newPlayer,inRoom+'summary',undefined,404);
  await request(newPlayer,'join',{code:'INCORRETO',character:'Íris'},404);
  const formatted=room.roomCode.match(/.{4}/g).join('-').toLowerCase();
  assert.equal((await request(newPlayer,'join',{code:formatted,character:'Íris',role:'gm'})).data.slug,room.slug);
  await request(newPlayer,'join',{code:room.roomCode,character:'Nome alternativo'});
  const joined=(await request(newPlayer,inRoom+'summary')).data;
  assert.equal(joined.character,'Íris');
  assert.equal(joined.role,'player');
  assert.equal(joined.roomCode,undefined);
  const secondRoom=(await request(newPlayer,'campaigns',{name:'Sala da Íris'},201)).data;
  assert.equal((await request(newPlayer,'c/'+secondRoom.slug+'/summary')).data.role,'gm');
  await request(registeredMaster,'join',{code:secondRoom.roomCode,character:'A viajante'});
  assert.equal((await request(registeredMaster,'c/'+secondRoom.slug+'/summary')).data.role,'player');
  assert.equal((await request(registeredMaster,inRoom+'summary')).data.role,'gm');
  await request(newPlayer,inRoom+'room-code',{},403);
  const playerIdentity=(await request(newPlayer,'campaigns')).data.user.id;
  const masterRoster=(await request(registeredMaster,inRoom+'roster')).data.members;
  assert.equal(masterRoster.find(member=>member.id===playerIdentity).login,'nova jogadora');
  await request(registeredMaster,inRoom+'member-status/'+playerIdentity,{active:false});
  await request(newPlayer,'join',{code:room.roomCode,character:'Íris'},403);
  const replacement=(await request(registeredMaster,inRoom+'room-code',{rotate:true})).data.code;
  assert.notEqual(replacement,room.roomCode);
  await request(newPlayer,'join',{code:room.roomCode,character:'Íris'},404);
  assert.ok((await request('','login',{identifier:'NOVA JOGADORA',password})).cookie);
  const identity=async cookie=>(await request(cookie,'campaigns')).data.user.id;
  const [j1Id,j2Id]=await Promise.all([identity(j1),identity(j2)]);
  await request(j1,inB+'summary',undefined,404);
  await request(j1,inA+'resources',{title:'Missão falsa',mode:'all'},403);
  await request(gm,inA+'resources',{kind:'message',title:'Mensagem antiga',mode:'all'},400);
  await request(gm,inA+'resources',{title:'Missão agendada',mode:'all',release:Date.now()+5000},400);
  await request(gm,inA+'schedule/unused',{},404);
  await request(gm,inA+'persona',{name:'NPC'},404);
  const channel=await fetch(base+'/api/'+inA+'events',{headers:{Cookie:j2}});
  assert.equal(channel.status,200);
  const reader=channel.body.getReader();
  assert.match(Buffer.from((await reader.read()).value).toString(),/conectado/);
  const privateMission={title:'Segredo',body:'Onde está o mapa?',targets:[j1Id],requestKey:'private-mission'};
  await request(gm,inA+'resources',{...privateMission,files:[{name:'mapa.txt',data:'dGVzdGU='}]},400);
  const secret=(await request(gm,inA+'resources',privateMission)).data;
  assert.equal((await request(gm,inA+'resources',privateMission)).data.id,secret.id);
  const privateEvent=await Promise.race([reader.read(),new Promise(resolve=>setTimeout(()=>resolve('sem evento'),1800))]);
  assert.equal(privateEvent,'sem evento');
  await reader.cancel();
  const mine=(await request(j1,inA+'resources/'+secret.id)).data;
  assert.equal(mine.receipts,undefined);
  await request(j2,inA+'resources/'+secret.id,undefined,404);
  assert.equal(mine.files,undefined);
  await request(j3,inB+'resources/'+secret.id,undefined,404);
  await request(gm,inA+'files/legacy',undefined,404);
  assert.equal((await request(j2,inA+'resources?q=Segredo')).data.items.length,0);
  assert.equal((await request(j2,inA+'summary')).data.unread,0);
  assert.equal((await request(j2,inA+'history')).data.items.length,0);
  await request(j1,inA+'read/'+secret.id,{});
  await request(j1,inA+'read/'+secret.id,{});
  assert.ok((await request(gm,inA+'resources/'+secret.id)).data.receipts[0].read);
  await request(gm,inA+'member-status/'+j2Id,{active:false});
  const published=(await request(gm,inA+'resources',{mode:'all',title:'Missão para ativos'})).data;
  assert.equal(published.count,1);
  await request(j2,inA+'summary',undefined,404);
  await request(gm,inA+'member-status/'+j2Id,{active:true});
  await request(j2,inA+'resources/'+published.id,undefined,404);
  const mission=(await request(gm,inA+'resources',{kind:'mission',targets:[j1Id,j2Id],title:'Relíquia',body:'Secreto',progress:'individual',state:'completed',priority:'high',due:100,objectives:[{title:'Antigo'}]})).data;
  const revealed=(await request(j1,inA+'resources/'+mission.id)).data;
  assert.deepEqual(revealed.detail,{progress:'individual',state:'available'});
  await request(j1,inA+'mission/'+mission.id,{title:'Alteração proibida'},403);
  await request(j1,inA+'complete-mission/'+mission.id,{},403);
  await request(j1,inA+'delete-mission/'+mission.id,{},403);
  await request(j1,inA+'read/'+mission.id,{});
  await request(gm,inA+'mission/'+mission.id,{title:'Relíquia restaurada',body:'Atualizada',state:'completed'});
  const edited=(await request(j1,inA+'resources/'+mission.id)).data;
  assert.equal(edited.title,'Relíquia restaurada');
  assert.equal(edited.body,undefined);
  assert.equal(edited.detail.state,'in_progress');
  assert.equal(edited.unread,false);
  assert.equal((await request(j2,inA+'resources/'+mission.id)).data.detail.state,'available');
  assert.ok((await request(j1,inA+'resources?state=in_progress')).data.items.some(item=>item.id===mission.id));
  assert.ok((await request(j2,inA+'resources?state=available')).data.items.some(item=>item.id===mission.id));
  const masterCard=(await request(gm,inA+'resources')).data.items.find(item=>item.id===mission.id);
  assert.equal(masterCard.readCount,1);
  assert.equal(masterCard.recipientCount,2);
  assert.equal((await request(j2,inA+'resources')).data.items.find(item=>item.id===mission.id).readCount,undefined);
  await request(gm,inA+'complete-mission/'+mission.id,{});
  await request(gm,inA+'complete-mission/'+mission.id,{});
  assert.equal((await request(j1,inA+'resources/'+mission.id)).data.detail.state,'completed');
  assert.equal((await request(j2,inA+'resources/'+mission.id)).data.detail.state,'completed');
  const ownHistory=(await request(j1,inA+'history')).data;
  assert.deepEqual(ownHistory.items.filter(item=>item.mission===mission.id).map(item=>item.action),['Missão concluída']);
  assert.deepEqual((await request(j2,inA+'history')).data.items.map(item=>item.mission),[mission.id]);
  assert.ok((await request(gm,inA+'history')).data.items.some(item=>item.mission===secret.id));
  assert.ok((await request(j1,inA+'history?before='+ownHistory.items[0].id)).data.items.every(item=>item.mission!==mission.id));
  const shared=(await request(gm,inA+'resources',{targets:[j1Id,j2Id],title:'Missão compartilhada'})).data;
  await request(j1,inA+'read/'+shared.id,{});
  assert.equal((await request(j2,inA+'resources/'+shared.id)).data.detail.state,'in_progress');
  await request(gm,inA+'mission/'+shared.id,{title:'Missão compartilhada revisada'});
  for(const viewer of [gm,j1,j2]) {
    const history=(await request(viewer,inA+'history')).data;
    assert.deepEqual(history.items.filter(item=>item.mission===shared.id).map(item=>item.action),['Missão atualizada']);
    const older=(await request(viewer,inA+'history?before='+history.items[0].id)).data;
    assert.ok(older.items.every(item=>item.mission!==shared.id));
  }
  await request(gm,inA+'delete-mission/'+shared.id,{});
  await request(j1,inA+'resources/'+shared.id,undefined,404);
  assert.ok((await request(j1,inA+'history')).data.items.every(item=>item.mission!==shared.id));
  await request(gm,inB+'member',{email:'um@example.com',role:'gm'});
  assert.equal((await request(j1,inB+'summary')).data.role,'player');
  assert.equal((await request(j1,inA+'summary')).data.role,'player');
  await request(j1,inB+'theme',{preset:'modern'},403);
  await request(gm,inB+'theme',{preset:'modern'});
  assert.equal((await request(j1,inA+'summary')).data.theme.preset,'arcane');
  await request(j1,'logout',{});
  await request(j1,inA+'summary',undefined,401);
  await stop();
  await boot();
  const reauthenticated=(await request('','login',{email:'um@example.com',password})).cookie;
  assert.equal((await request(reauthenticated,inA+'resources/'+mission.id)).data.detail.state,'completed');
  assert.equal((await request(reauthenticated,inA+'resources/'+secret.id)).data.title,'Segredo');
});

